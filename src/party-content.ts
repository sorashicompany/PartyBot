export function partyReplyForPrompt(seed: number, promptText?: string): string {
  const key = (promptText || "").trim().toLocaleLowerCase("ru-RU");
  const prompt = PARTY_PROMPTS.find((item) => item.text.toLocaleLowerCase("ru-RU") === key);
  const pool = prompt?.replies.length ? prompt.replies : PARTY_GENERIC_ANSWERS;
  return pool[Math.abs(seed) % pool.length] || PARTY_GENERIC_ANSWERS[0];
}
